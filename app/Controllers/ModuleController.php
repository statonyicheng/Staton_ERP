        $meta = $catalog[$key] ?? ['未知模組', 'ERP', '此模組尚未定義。', []];

        return view('modules/placeholder', [
            'key'         => $key,
            'title'       => $meta[0],
            'subsystem'   => $meta[1],
            'description' => $meta[2],
            'features'    => $meta[3],
        ]);
